/** Iniciales (hasta dos) de un nombre, en mayúsculas. */
export function initials(name: string): string {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((p) => p[0]?.toUpperCase())
    .join('');
}

/** Tono estable (0-359) a partir de un texto, para el color del avatar de iniciales. */
export function authorHue(key: string): number {
  let h = 0;
  for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) % 360;
  return h;
}
